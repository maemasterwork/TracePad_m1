#!/usr/bin/env python3
"""Generate apps/web/src/db/types.ts from the migrated database.

  python3 supabase/gen_types.py              # spins up a scratch PostgreSQL, applies all migrations, writes types.ts
  python3 supabase/gen_types.py --out FILE   # same, different output file
  PGHOST=... PGPORT=... PGUSER=... PGDATABASE=... python3 supabase/gen_types.py   # introspect an existing database

Row types for every public table, Args/Returns for every public function that signed-in users may call.
"""
import json, os, re, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_OUT = HERE.parent / "apps" / "web" / "src" / "db" / "types.ts"

# Nicer return types for functions that return a documented jsonb shape.
RETURN_OVERRIDES = {
    "save_progress": "SaveProgressResult",
    "export_my_data": "ExportedData",
}
ARG_OVERRIDES = {("save_progress", "items"): "SaveProgressItem[]"}

TS = {"uuid": "string", "text": "string", "varchar": "string", "bpchar": "string", "name": "string", "citext": "string",
      "bool": "boolean", "int2": "number", "int4": "number", "int8": "number", "float4": "number", "float8": "number",
      "numeric": "number", "timestamptz": "string", "timestamp": "string", "date": "string", "time": "string",
      "interval": "string", "json": "Json", "jsonb": "Json", "void": "undefined", "bytea": "string"}


def psql_json(sql):
    out = subprocess.run(["psql", "-X", "-At", "-v", "ON_ERROR_STOP=1", "-c", sql], capture_output=True, text=True)
    if out.returncode:
        sys.exit(out.stderr)
    return json.loads(out.stdout.strip() or "null")


def ts_type(udt):
    arr = udt.startswith("_")
    base = udt[1:] if arr else udt
    t = TS.get(base)
    if t is None:
        sys.exit(f"unmapped postgres type: {udt}")
    return f"{t}[]" if arr else t


def check_unions(table):
    """column -> list of allowed strings, from CHECK (col = ANY (ARRAY['a'::text, ...])) constraints."""
    rows = psql_json(f"""select coalesce(json_agg(pg_get_constraintdef(oid)), '[]') from pg_constraint
                         where conrelid = 'public.{table}'::regclass and contype = 'c'""")
    res = {}
    for d in rows:
        for m in re.finditer(r"\(?(\w+)\)?(?:::text)? = ANY \(\(?ARRAY\[(.*?)\]", d):
            res[m.group(1)] = re.findall(r"'([^']*)'", m.group(2))
    return res


def main():
    out = DEFAULT_OUT
    if "--out" in sys.argv:
        out = Path(sys.argv[sys.argv.index("--out") + 1])
    if "PGHOST" not in os.environ:
        sys.exit(subprocess.call([str(HERE / "tests" / "scratch_db.sh"), sys.executable, __file__, "--out", str(out)]))

    tables = psql_json("""select coalesce(json_agg(json_build_object('name', c.relname, 'cols', (
        select json_agg(json_build_object('name', a.attname, 'udt', t.typname, 'notnull', a.attnotnull,
               'default', a.atthasdef, 'identity', a.attidentity <> '', 'generated', a.attgenerated <> '') order by a.attnum)
        from pg_attribute a join pg_type t on t.oid = a.atttypid
        where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped)) order by c.relname), '[]')
        from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind = 'r'""")
    funcs = psql_json("""select coalesce(json_agg(json_build_object('name', p.proname, 'names', p.proargnames,
        'modes', p.proargmodes, 'ntypes', (select json_agg(format_type(t, null) order by o) from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality u(t, o)),
        'utypes', (select json_agg(ty.typname order by o) from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality u(t, o) join pg_type ty on ty.oid = u.t),
        'ndefaults', p.pronargdefaults, 'nargs', p.pronargs, 'ret', rt.typname, 'set', p.proretset) order by p.proname), '[]')
        from pg_proc p join pg_namespace n on n.oid = p.pronamespace join pg_type rt on rt.oid = p.prorettype
        where n.nspname = 'public' and p.prokind = 'f' and rt.typname <> 'trigger'
          and has_function_privilege('authenticated', p.oid, 'execute')""")

    L = ["// GENERATED by supabase/gen_types.py from the migrations. Do not edit by hand; re-run the script.",
         "// bigint columns (progress.client_ts, audit_log.id, ...) are typed as number: they stay below 2^53.",
         "",
         "export type Json = string | number | boolean | null | { [key: string]: Json } | Json[];", ""]
    row_names = []
    L.append("export interface Database {\n  public: {\n    Tables: {")
    for t in tables:
        unions = check_unions(t["name"])
        def col_t(c):
            if c["name"] in unions:
                return " | ".join(f"'{v}'" for v in unions[c["name"]])
            return ts_type(c["udt"])
        L.append(f"      {t['name']}: {{")
        L.append("        Row: {")
        for c in t["cols"]:
            L.append(f"          {c['name']}: {col_t(c)}{'' if c['notnull'] else ' | null'}")
        L.append("        }")
        for kind in ("Insert", "Update"):
            L.append(f"        {kind}: {{")
            for c in t["cols"]:
                if c["generated"]:
                    continue
                opt = kind == "Update" or c["default"] or c["identity"] or not c["notnull"]
                L.append(f"          {c['name']}{'?' if opt else ''}: {col_t(c)}{'' if c['notnull'] else ' | null'}")
            L.append("        }")
        L.append("      }")
    L.append("    }\n    Functions: {")
    for f in funcs:
        names, modes = f["names"] or [], f["modes"]
        n = f["nargs"]
        types = f["utypes"] or []
        args, rets = [], []
        for i, ty in enumerate(types):
            mode = modes[i] if modes else "i"
            name = names[i] if i < len(names) and names[i] else f"arg{i}"
            if mode in ("i", "b", "v"):
                args.append((name, ty))
            else:
                rets.append((name, ty))
        L.append(f"      {f['name']}: {{")
        if args:
            first_default = len(args) - f["ndefaults"]
            L.append("        Args: {")
            for i, (name, ty) in enumerate(args):
                t = ARG_OVERRIDES.get((f["name"], name)) or ts_type(ty)
                L.append(f"          {name}{'?' if i >= first_default else ''}: {t}")
            L.append("        }")
        else:
            L.append("        Args: Record<string, never>")
        if rets:
            body = "; ".join(f"{name}: {ts_type(ty)}" for name, ty in rets)
            L.append(f"        Returns: {{ {body} }}[]")
        else:
            r = RETURN_OVERRIDES.get(f["name"]) or ts_type(f["ret"])
            L.append(f"        Returns: {r}{'[]' if f['set'] else ''}")
        L.append("      }")
    L.append("    }\n  }\n}\n")

    L += ["type PublicTables = Database['public']['Tables']",
          "export type TableName = keyof PublicTables",
          "export type Row<T extends TableName> = PublicTables[T]['Row']",
          "export type Insert<T extends TableName> = PublicTables[T]['Insert']",
          "export type Update<T extends TableName> = PublicTables[T]['Update']",
          "export type FunctionName = keyof Database['public']['Functions']",
          "export type FunctionArgs<F extends FunctionName> = Database['public']['Functions'][F]['Args']",
          "export type FunctionReturns<F extends FunctionName> = Database['public']['Functions'][F]['Returns']", ""]
    for t in tables:
        name = "".join(p.capitalize() for p in t["name"].split("_"))
        L.append(f"export type {name}Row = Row<'{t['name']}'>")
    L += ["",
          "// Hand-written shapes for the jsonb results (see docs/database.md).",
          "export interface SaveProgressItem { key: string; data: { [key: string]: Json }; client_ts: number }",
          "export interface StoredProgress { key: string; data: { [key: string]: Json }; client_ts: number; rev: number; updated_at: string }",
          "export interface SaveProgressResult {",
          "  applied: string[]",
          "  conflicts: { key: string; stored: StoredProgress }[]",
          "  rejected: { key: string | null; reason: string }[]",
          "}",
          "export interface ExportedData {",
          "  exported_at: string",
          "  account: { id: string; email: string | null } | null",
          "  profile: ProfilesRow | null",
          "  progress: ProgressRow[]",
          "  enrollments: EnrollmentsRow[]",
          "  classes: ClassesRow[]",
          "  assignments: AssignmentsRow[]",
          "  analytics_events: AnalyticsEventsRow[]",
          "  audit_log: AuditLogRow[]",
          "  rate_limits: RateLimitsRow[]",
          "}", ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L))
    print(f"wrote {out}")


main()
